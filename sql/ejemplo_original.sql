--CREATE OR REPLACE VIEW `shape-mhs-1.silver.master_tracker_export` AS
SELECT j.job_number                                                                       AS `Job Number`  
     , TRIM(jt.name)                                                                        AS `Job Type` 
     , TRIM(bu.name)                                                                        AS `Business Unit`
     , p.number                                                                             AS `Project`
     , CASE WHEN j.recall_for_id IS NULL THEN FALSE ELSE TRUE END                           AS `Recall`
     , TRIM(t.name)                                                                         AS `Lead Generated By`
     , j.job_generated_lead_source_job_id                                                   AS `Lead Generated From`
     , COALESCE(il.sub_total_lead,0)                                                        AS `Sales from Leads Created`
     , COALESCE(it.total_invoice,0)                                                         AS `Total`
     , DATE(`pph-central`.settings.fn_convert_utc_localtz(j.completed_on,1))                AS `Completion Date`     
     , j.customer_id                                                                        AS `Customer Id`
     , TRIM(c.name)                                                                         AS `Customer Name` 
     , TRIM(ts.name)                                                                        AS `Sold By` 
     , ARRAY_TO_STRING(IFNULL(ti.assigned_technicians, []), ', ')                           AS `Assigned Technicians`
     , TRIM(ti.primary_technician)                                                          AS `Primary Technician`
     , es.subtotal                                                                          AS `Estimate Sales Subtotal`
     , TRIM(ca.name)                                                                        AS `Job Campaign`
     , ROUND(ii.sold_hours,2)                                                               AS `Sould Hours`
  FROM `shape-mhs-1.servicetitan_shape_mhs_1.job`                                                   j 
  LEFT JOIN `shape-mhs-1.bronze.job_type`                                                jt
    ON jt.id                                                                                = j.job_type_id
  LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.business_unit`                                    bu
    ON bu.id                                                                                = j.business_unit_id
  LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.project`                                          p
    ON p.id                                                                                 = j.project_id
  LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.employee`                                         e
    ON e.id                                                                                 = j.job_generated_lead_source_employee_id
  LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.technician`                                       t 
    ON t.id                                                                                 = j.job_generated_lead_source_employee_id 
  LEFT JOIN 
       (
        SELECT invoice_lead.job_id                                                          AS job_id
             , SUM(invoice_lead.sub_total)                                                  AS sub_total_lead
          FROM `shape-mhs-1.servicetitan_shape_mhs_1.invoice`                                       invoice_lead
         GROUP BY invoice_lead.job_id
       )                                                                                    il
    ON il.job_id                                                                            = j.job_generated_lead_source_job_id
  LEFT JOIN 
       (
        SELECT invoice_total.job_id                                                         AS job_id
             , SUM(invoice_total.sub_total)                                                 AS total_invoice
          FROM `shape-mhs-1.servicetitan_shape_mhs_1.invoice`                                       invoice_total
         GROUP BY invoice_total.job_id
       )                                                                                    it
    ON it.job_id                                                                            = j.id    
  LEFT JOIN 
       (
        SELECT invoice.job_id                                                               AS job_id
--             , SUM(i2.price)                                                              AS total_items
             , SUM(invoice_items.sold_hours)                                                AS sold_hours  
          FROM `shape-mhs-1.servicetitan_shape_mhs_1.invoice`                               invoice
          LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.invoice_item`                     invoice_items
            ON invoice_items.invoice_id                                                     = invoice.id
         WHERE invoice_items.active                                                         IS TRUE 
         GROUP BY                                                                           invoice.job_id
       )                                                                                    ii
    ON ii.job_id                                                                            = j.id   
  LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.customer`                                 c
    ON c.id                                                                                 = j.customer_id
  LEFT JOIN 
       (
        SELECT js.job_id                                                                    AS job_id
             , ARRAY_AGG(DISTINCT IFNULL(t.name, ''))                                       AS assigned_technicians
             , ARRAY_AGG(IFNULL(t.name, '') ORDER BY js.split DESC LIMIT 1)[SAFE_OFFSET(0)] AS primary_technician
          FROM `shape-mhs-1.servicetitan_shape_mhs_1.job_split`                             js
          LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.technician`                       
            ON js.technician_id                                                             = t.id
         GROUP BY                                                                           js.job_id
       )                                                                                    ti 
    ON ti.job_id                                                                            = j.id
  LEFT JOIN `shape-mhs-1.servicetitan_shape_mhs_1.technician`                               ts 
    ON ts.id                                                                                = j.sold_by_id    
  LEFT JOIN 
       (
        SELECT job_id                                                                       AS job_id
             , SUM(subtotal)                                                                AS subtotal
          FROM `shape-mhs-1.servicetitan_shape_mhs_1.estimate`                              estimate
         WHERE sold_on                                                                      IS NOT NULL 
           AND active                                                                       IS TRUE
         GROUP BY                                                                           job_id 
       )                                                                                    es 
    ON es.job_id                                                                            = j.id      
  LEFT JOIN `shape-mhs-1.bronze.campaign`                                                   ca
    ON ca.id                                                                                = j.campaign_id
WHERE j.job_status                                                                          = 'Completed'
ORDER BY j.completed_on